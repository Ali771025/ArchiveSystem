export const resolveRolePermissions = (roles: string[]): PermissionKey[] => {
  const permissions = new Set<PermissionKey>();

  roles.forEach((role) => {
    (permissionsByRole[role.trim().toLowerCase()] ?? []).forEach((permission) => permissions.add(permission));
  });

  return Array.from(permissions);
};
